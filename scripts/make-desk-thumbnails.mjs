import sharp from 'sharp';
import { readdir, writeFile } from 'node:fs/promises';

const source = 'public/images/projects';
const files = (await readdir(source)).filter((file) => file.endsWith('.webp')).sort();
const width = 320;
const height = 180;
const columns = 4;
const tiles = await Promise.all(
  files.map(async (file, index) => ({
    input: await sharp(source + '/' + file)
      .resize(width, height, { position: 'attention' })
      .png()
      .toBuffer(),
    left: (index % columns) * width,
    top: Math.floor(index / columns) * height,
  }))
);

await sharp({
  create: {
    width: width * columns,
    height: height * Math.ceil(files.length / columns),
    channels: 3,
    background: '#18191d',
  },
})
  .composite(tiles)
  .webp({ quality: 77 })
  .toFile('public/images/hero/desk-projects.webp');

const names = files.map((file) => file.replace(/\.webp$/, ''));
await writeFile(
  'components/desk/thumbnailAtlas.ts',
  '// Generated by scripts/make-desk-thumbnails.mjs.\n' +
    'export const THUMBNAIL_ATLAS = ' +
    JSON.stringify({ width, height, columns, names }) +
    ' as const;\n'
);
