import sharp from 'sharp';
import { readdir, writeFile } from 'node:fs/promises';

// Two atlases of the project thumbnails for the desk monitors: an HD one
// for desktop screens (textures up to 2048 px) and a lighter one for phones.
const source = 'public/images/projects';
const files = (await readdir(source)).filter((file) => file.endsWith('.webp')).sort();
const columns = 4;
const atlases = {
  hd: { width: 800, height: 450, file: 'desk-projects-hd.webp', quality: 80 },
  sd: { width: 480, height: 270, file: 'desk-projects.webp', quality: 80 },
};

for (const { width, height, file, quality } of Object.values(atlases)) {
  const tiles = await Promise.all(
    files.map(async (name, index) => ({
      input: await sharp(source + '/' + name)
        .resize(width, height, { position: 'attention', kernel: 'lanczos3' })
        .png()
        .toBuffer(),
      left: (index % columns) * width,
      top: Math.floor(index / columns) * height,
    }))
  );
  await sharp({
    create: {
      width: width * columns,
      height: height * Math.ceil(files.length / columns),
      channels: 3,
      background: '#0d0f14',
    },
  })
    .composite(tiles)
    .webp({ quality, smartSubsample: true })
    .toFile('public/images/hero/' + file);
}

const names = files.map((file) => file.replace(/\.webp$/, ''));
const meta = Object.fromEntries(
  Object.entries(atlases).map(([key, { width, height, file }]) => [key, { width, height, src: '/images/hero/' + file }])
);
await writeFile(
  'components/desk/thumbnailAtlas.ts',
  '// Generated by scripts/make-desk-thumbnails.mjs.\n' +
    'export const THUMBNAIL_ATLAS = ' +
    JSON.stringify({ columns, names, ...meta }) +
    ' as const;\n'
);
